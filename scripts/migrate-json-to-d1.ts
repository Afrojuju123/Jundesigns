/**
 * Data Migration Script: JSON to Cloudflare D1
 *
 * Reads `data/bookings.json` and `data/admin-config.json` and generates
 * `migrations/0002_seed_data.sql` with parameterized SQL statements.
 *
 * Can also execute directly against the local or D1 database.
 */

import fs from "node:fs";
import path from "node:path";

function escapeSqlString(val: string | null | undefined): string {
  if (val === null || val === undefined) return "NULL";
  return `'${val.replace(/'/g, "''")}'`;
}

function escapeSqlNumber(val: number | null | undefined): string {
  if (val === null || val === undefined) return "NULL";
  return String(val);
}

export function generateSeedSql(): string {
  const statements: string[] = [
    "-- Cloudflare D1 Data Migration from JSON store",
    "-- Generated by scripts/migrate-json-to-d1.ts",
    "",
  ];

  // 1. Admin Config
  const configPath = path.resolve(process.cwd(), "data/admin-config.json");
  if (fs.existsSync(configPath)) {
    const rawConfig = JSON.parse(fs.readFileSync(configPath, "utf8"));
    const capacity = rawConfig.capacityPerSlot ?? 8;
    const blockedDates = JSON.stringify(rawConfig.blockedDates ?? []);
    const policy = rawConfig.cancellationPolicyText ?? "";

    statements.push(
      `INSERT OR REPLACE INTO admin_config (id, capacity_per_slot, blocked_dates, cancellation_policy_text, updated_at) VALUES (1, ${capacity}, ${escapeSqlString(blockedDates)}, ${escapeSqlString(policy)}, CURRENT_TIMESTAMP);`
    );
  }

  // 2. Bookings
  const bookingsPath = path.resolve(process.cwd(), "data/bookings.json");
  if (fs.existsSync(bookingsPath)) {
    const bookings = JSON.parse(fs.readFileSync(bookingsPath, "utf8"));
    for (const b of bookings) {
      const phone = [b.customerCountry, b.customerPhone].filter(Boolean).join(" ");
      statements.push(
        `INSERT OR REPLACE INTO bookings (
  id, reference, workshop_slug, date, slot, guests, status,
  customer_name, customer_email, customer_phone, special_requests,
  amount_paid, currency, pesapal_order_tracking_id, pesapal_merchant_reference,
  payment_method, hold_expires_at, created_at, updated_at, reminder_sent_at,
  cancelled_at, refund_amount, refund_reason
) VALUES (
  ${escapeSqlString(b.id)},
  ${escapeSqlString(b.reference)},
  ${escapeSqlString(b.workshopSlug)},
  ${escapeSqlString(b.date)},
  ${escapeSqlString(b.slot)},
  ${escapeSqlNumber(b.guests)},
  ${escapeSqlString(b.status)},
  ${escapeSqlString(b.customerName)},
  ${escapeSqlString(b.customerEmail)},
  ${escapeSqlString(phone || null)},
  ${escapeSqlString(b.note || b.specialRequests || null)},
  ${escapeSqlNumber(b.amountRwf || b.amountPaid || 0)},
  ${escapeSqlString(b.currency || "RWF")},
  ${escapeSqlString(b.pesapalOrderTrackingId || null)},
  ${escapeSqlString(b.pesapalMerchantReference || b.paymentReference || null)},
  ${escapeSqlString(b.paymentMethod || b.paymentProvider || null)},
  ${escapeSqlString(b.holdExpiresAt || null)},
  ${escapeSqlString(b.createdAt || new Date().toISOString())},
  ${escapeSqlString(b.updatedAt || new Date().toISOString())},
  ${escapeSqlString(b.reminderEmailSentAt || b.reminderSentAt || null)},
  ${escapeSqlString(b.cancelledAt || null)},
  ${escapeSqlNumber(b.refundAmount || null)},
  ${escapeSqlString(b.refundReason || null)}
);`
      );
    }
  }

  return statements.join("\n\n");
}

function run() {
  const sql = generateSeedSql();
  const outputPath = path.resolve(process.cwd(), "migrations/0002_seed_data.sql");
  fs.writeFileSync(outputPath, sql, "utf8");
  console.log(`Generated migration SQL at: ${outputPath}`);
}

run();
